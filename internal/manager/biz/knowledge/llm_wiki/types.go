// WikiPage and WikiLink are filesystem-oriented Knowledge IR types. Markdown
// is authoritative; the similarly named wiki_* SQLite rows are rebuildable
// catalog and query caches.
type WikiPage struct {
	ID             string
	Type           string
	Title          string
	Description    string
	Aliases        []string
	Language       string
	SourceVersions []uint64
	Related        []string
	RelativePath   string
	BodySHA256     string
	CreatedAt      time.Time
	UpdatedAt      time.Time
}

type WikiLink struct {
	FromPageID string
	ToPageID   string
	Type       string
}

type ArtifactBatch struct {
	Pages                []WikiPage
	Links                []WikiLink
	PageSourceVersionIDs map[string][]uint64
	DeletedPageIDs       []string
}

func makeArtifactBatch(pages []*model.Page, versions map[string][]uint64, relations []*model.PageRelation, deleted []string) ArtifactBatch {
	batch := ArtifactBatch{Pages: make([]WikiPage, 0, len(pages)), Links: make([]WikiLink, 0, len(relations)), PageSourceVersionIDs: versions, DeletedPageIDs: deleted}
	for _, page := range pages {
		if page == nil {
			continue
		}
		batch.Pages = append(batch.Pages, WikiPage{
			ID: page.PageID, Type: page.PageType, Title: page.Title, Aliases: decodeStringList(page.AliasesJSON),
			Language: page.Language, SourceVersions: versions[page.PageID], RelativePath: page.RelativePath,
			BodySHA256: page.BodySHA256, CreatedAt: page.CreatedAt, UpdatedAt: page.UpdatedAt,
		})
	}
	for _, relation := range relations {
		if relation != nil {
			batch.Links = append(batch.Links, WikiLink{FromPageID: relation.FromPageID, ToPageID: relation.ToPageID, Type: relation.RelationType})
		}
	}
	return batch
}

