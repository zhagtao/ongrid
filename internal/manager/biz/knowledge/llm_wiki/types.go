type Summarizer interface {
	Summarize(ctx context.Context, instructions, chunkID, text string) (string, error)
}

// BatchSummarizer is optional so embedders and tests that only implement the
// original single-input interface continue to work. The compiler falls back
// to single-chunk calls when this capability is unavailable.
type BatchSummarizer interface {
	SummarizeBatch(ctx context.Context, instructions string, chunks []BatchChunkInput, maxOutputTokens int) (string, llm.Usage, error)
}

// SourceSynthesizer optionally combines a complete small-source leaf batch
// into one validated source summary and topic-plan response. It is optional so
// existing embedders keep the hierarchy + planner path unchanged.
type SourceSynthesizer interface {
	SynthesizeSource(ctx context.Context, instructions, input string) (string, llm.Usage, error)
}

// VersionedSummarizer lets cache keys follow an explicitly configured model
// deployment. Implementations that do not expose a version use a conservative
// type-based fallback and can be upgraded without changing the interface.
type VersionedSummarizer interface {
	ModelVersion() string
}

// UsageSummarizer is implemented by summarizers that can return the provider
// usage for the request. The base Summarizer interface stays small so custom
// test and embedding implementations do not need to know about accounting.
type UsageSummarizer interface {
	SummarizeWithUsage(ctx context.Context, instructions, chunkID, text string) (string, llm.Usage, error)
}

// TokenUsageRecorder starts an existing chat-session transcript for one
// compile job. Implementations belong to the composition root so this domain
// does not depend directly on the AIOps bounded context.
type TokenUsageRecorder interface {
	Start(ctx context.Context, jobID uint64) (TokenUsageSink, error)
}

type TokenUsageSink interface {
	Record(ctx context.Context, usage llm.Usage) error
	Close(ctx context.Context) error
}

